"""Webhook endpoints (REL-39, ADR-0015, api-contract.md). The API key (401) is checked by the middleware in app.main."""

import uuid
from datetime import UTC, datetime
from typing import Annotated, Literal

import sqlalchemy as sa
from fastapi import APIRouter, Query, Request
from pydantic import BaseModel, Field, StringConstraints
from sqlalchemy.orm import Session

from app.api.cursor import decode_cursor, encode_cursor
from app.api.schemas import iso_utc
from app.db.models import WebhookDelivery, WebhookDeliveryAttempt, WebhookSubscription
from app.errors import ApiError
from app.webhooks.config import get_webhook_settings
from app.webhooks.store import create_subscription
from app.webhooks.targets import is_allowed_target, parse_allowed_hosts

router = APIRouter()

EventType = Literal[
    "payment.received",
    "payment.authorized",
    "payment.captured",
    "payment.declined",
    "payment.failed",
    "payment.final",
]
DeliveryStatus = Literal["pending", "delivered", "failed"]
DEFAULT_LIMIT = 20  # the same page size and maximum as GET /payments
MAX_LIMIT = 100


class SubscriptionCreate(BaseModel):
    url: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=2048)]
    event_types: Annotated[list[EventType], Field(min_length=1)]


class SubscriptionResponse(BaseModel):
    id: str
    url: str
    event_types: list[str]
    active: bool
    created_at: str


class SubscriptionCreated(SubscriptionResponse):
    secret: str  # the only response that ever carries it


class SubscriptionListResponse(BaseModel):
    items: list[SubscriptionResponse]


class DeliveryResponse(BaseModel):
    id: int
    subscription_id: str
    event_id: int
    event_type: str
    attempt: int
    status: str
    next_attempt_at: str | None  # only while the delivery is pending
    last_status_code: int | None
    last_error: str | None
    created_at: str
    updated_at: str


class AttemptResponse(BaseModel):
    attempt: int
    status_code: int | None
    error: str | None
    duration_ms: int
    attempted_at: str


class DeliveryDetailResponse(DeliveryResponse):
    attempts: list[AttemptResponse]


class DeliveryListResponse(BaseModel):
    items: list[DeliveryResponse]
    next_cursor: str | None  # null on the last page


class DeliverySummaryResponse(BaseModel):
    delivered: int
    failed: int
    pending: int
    success_rate: float | None  # delivered / (delivered + failed); null when no delivery is final
    since: str | None
    until: str | None
    subscription_id: str | None


def _body(row: WebhookSubscription) -> SubscriptionResponse:
    return SubscriptionResponse(
        id=str(row.id),
        url=row.url,
        event_types=list(row.event_types),
        active=row.active,
        created_at=iso_utc(row.created_at),
    )


def _subscription_id(raw: str) -> uuid.UUID:
    try:
        value = uuid.UUID(raw)
        if len(raw) != 36:  # UUID() also accepts braces, urn: prefixes and bare hex
            raise ValueError(raw)
    except ValueError:
        raise ApiError(404, "not_found", "subscription not found") from None
    return value


@router.post(
    "/webhooks/subscriptions",
    status_code=201,
    response_model=SubscriptionCreated,
    summary="Register a webhook subscription",
    description="`url` must be http or https to a host in `WEBHOOK_ALLOWED_HOSTS`, otherwise 422 "
    "`webhook_target_not_allowed` and nothing is fetched or stored. `event_types` are payment lifecycle types only. "
    "The response carries the signing `secret`, generated by Relay; it is returned only here and never again.",
)
def create_webhook_subscription(body: SubscriptionCreate, request: Request) -> SubscriptionCreated:
    if not is_allowed_target(body.url, parse_allowed_hosts(get_webhook_settings().webhook_allowed_hosts)):
        raise ApiError(422, "webhook_target_not_allowed", "url must be http or https to an allowed host")
    with Session(request.app.state.engine) as session, session.begin():
        row = create_subscription(session, body.url, list(body.event_types))
        return SubscriptionCreated(**_body(row).model_dump(), secret=row.secret)


@router.get(
    "/webhooks/subscriptions",
    response_model=SubscriptionListResponse,
    summary="List webhook subscriptions, newest first",
    description="Never includes the secret.",
)
def list_webhook_subscriptions(request: Request) -> SubscriptionListResponse:
    with Session(request.app.state.engine) as session:
        rows = session.scalars(
            sa.select(WebhookSubscription).order_by(
                WebhookSubscription.created_at.desc(), WebhookSubscription.id.desc()
            )
        ).all()
        return SubscriptionListResponse(items=[_body(row) for row in rows])


@router.get(
    "/webhooks/subscriptions/{subscription_id}",
    response_model=SubscriptionResponse,
    summary="Get one webhook subscription",
    description="Never includes the secret.",
)
def get_webhook_subscription(subscription_id: str, request: Request) -> SubscriptionResponse:
    with Session(request.app.state.engine) as session:
        row = session.get(WebhookSubscription, _subscription_id(subscription_id))
        if row is None:
            raise ApiError(404, "not_found", "subscription not found")
        return _body(row)


@router.delete(
    "/webhooks/subscriptions/{subscription_id}",
    response_model=SubscriptionResponse,
    summary="Deactivate a webhook subscription",
    description="Sets `active` to false; repeating it is harmless. Deliveries still waiting are marked failed "
    "(`subscription_inactive`) without a request.",
)
def deactivate_webhook_subscription(subscription_id: str, request: Request) -> SubscriptionResponse:
    with Session(request.app.state.engine) as session, session.begin():
        row = session.get(WebhookSubscription, _subscription_id(subscription_id))
        if row is None:
            raise ApiError(404, "not_found", "subscription not found")
        row.active = False
        session.flush()
        return _body(row)


@router.get(
    "/webhooks/deliveries",
    response_model=DeliveryListResponse,
    summary="The delivery log, newest first",
    description="One entry per delivery (one event to one subscription) with its attempt count, status and the last "
    "response (`last_status_code`, or `last_error` for a timeout or connection error). Keyset pagination on "
    "`(created_at, id)` descending, like `GET /payments`: pass `next_cursor` as `cursor` for the next page; it is null "
    "on the last page. `limit` is the page size (1 to 100); the filters apply to every page. A malformed `cursor` is "
    "400 `malformed_request`. Rows are kept for `WEBHOOK_LOG_RETENTION_DAYS` after they are delivered or failed.",
)
def list_webhook_deliveries(
    request: Request,
    subscription_id: Annotated[uuid.UUID | None, Query()] = None,
    status: Annotated[DeliveryStatus | None, Query()] = None,
    limit: Annotated[int, Query(ge=1, le=MAX_LIMIT)] = DEFAULT_LIMIT,
    cursor: Annotated[str | None, Query(description="The opaque `next_cursor` of the previous page")] = None,
) -> DeliveryListResponse:
    after = _after(cursor) if cursor is not None else None
    query = (
        sa.select(WebhookDelivery)
        .order_by(WebhookDelivery.created_at.desc(), WebhookDelivery.id.desc())
        .limit(limit + 1)
    )
    if subscription_id is not None:
        query = query.where(WebhookDelivery.subscription_id == subscription_id)
    if status is not None:
        query = query.where(WebhookDelivery.status == status)
    if after is not None:
        query = query.where(sa.tuple_(WebhookDelivery.created_at, WebhookDelivery.id) < sa.tuple_(*after))
    with Session(request.app.state.engine) as session:
        rows = list(session.scalars(query))
    page = rows[:limit]
    return DeliveryListResponse(
        items=[_delivery_body(row) for row in page],
        next_cursor=encode_cursor(page[-1].created_at, str(page[-1].id)) if len(rows) > limit else None,
    )


def _after(cursor: str) -> tuple[datetime, int]:
    created_at, key = decode_cursor(cursor)
    try:
        delivery_id = int(key)
    except ValueError:
        delivery_id = 0
    if not 0 < delivery_id < 2**63:  # the id column is a BIGINT
        raise ApiError(400, "malformed_request", "cursor is malformed")
    return created_at, delivery_id


def _delivery_body(row: WebhookDelivery) -> DeliveryResponse:
    return DeliveryResponse(
        id=row.id,
        subscription_id=str(row.subscription_id),
        event_id=row.event_id,
        event_type=row.event_type,
        attempt=row.attempt,
        status=row.status,
        next_attempt_at=iso_utc(row.next_attempt_at) if row.status == "pending" else None,
        last_status_code=row.last_status_code,
        last_error=row.last_error,
        created_at=iso_utc(row.created_at),
        updated_at=iso_utc(row.updated_at),
    )


def _utc(moment: datetime | None) -> datetime | None:
    if moment is None:
        return None
    return moment.replace(tzinfo=UTC) if moment.tzinfo is None else moment.astimezone(UTC)


@router.get(
    "/webhooks/deliveries/summary",
    response_model=DeliverySummaryResponse,
    summary="Webhook delivery success rate",
    description="Counts of `delivered`, `failed` and `pending` deliveries in the window [`since`, `until`) and "
    "`success_rate` = delivered / (delivered + failed), null when no delivery is final. A delivered or failed "
    "delivery falls in the window by its `updated_at` (when it finished), a pending one by its `created_at`. "
    "`since` and `until` are ISO 8601 (a time without a zone is UTC) and optional; `subscription_id` limits the "
    "count to one subscription. Computed from the delivery log, so rows past `WEBHOOK_LOG_RETENTION_DAYS` are gone.",
)
def webhook_delivery_summary(
    request: Request,
    since: Annotated[datetime | None, Query()] = None,
    until: Annotated[datetime | None, Query()] = None,
    subscription_id: Annotated[uuid.UUID | None, Query()] = None,
) -> DeliverySummaryResponse:
    begin, stop = _utc(since), _utc(until)
    if begin is not None and stop is not None and begin >= stop:
        raise ApiError(422, "validation_failed", "`since` must be before `until`")
    moment = sa.case(
        (WebhookDelivery.status == "pending", WebhookDelivery.created_at), else_=WebhookDelivery.updated_at
    )
    query = sa.select(WebhookDelivery.status, sa.func.count()).group_by(WebhookDelivery.status)
    if begin is not None:
        query = query.where(moment >= begin)
    if stop is not None:
        query = query.where(moment < stop)
    if subscription_id is not None:
        query = query.where(WebhookDelivery.subscription_id == subscription_id)
    with Session(request.app.state.engine) as session:
        counts = dict(session.execute(query).all())
    delivered, failed = counts.get("delivered", 0), counts.get("failed", 0)
    return DeliverySummaryResponse(
        delivered=delivered,
        failed=failed,
        pending=counts.get("pending", 0),
        success_rate=round(delivered / (delivered + failed), 4) if delivered + failed else None,
        since=iso_utc(begin) if begin else None,
        until=iso_utc(stop) if stop else None,
        subscription_id=str(subscription_id) if subscription_id else None,
    )


@router.get(
    "/webhooks/deliveries/{delivery_id}",
    response_model=DeliveryDetailResponse,
    summary="One delivery with every attempt",
    description="The delivery plus `attempts`, in order: for each attempt its number, the HTTP `status_code` (null "
    "without a response), `error` (the same values as `last_error`), `duration_ms` and `attempted_at`. Attempts are "
    "deleted with their delivery by the retention cleanup. An unknown id is 404.",
)
def get_webhook_delivery(delivery_id: int, request: Request) -> DeliveryDetailResponse:
    with Session(request.app.state.engine) as session:
        row = session.get(WebhookDelivery, delivery_id)
        if row is None:
            raise ApiError(404, "not_found", "delivery not found")
        attempts = session.scalars(
            sa.select(WebhookDeliveryAttempt)
            .where(WebhookDeliveryAttempt.delivery_id == delivery_id)
            .order_by(WebhookDeliveryAttempt.attempt, WebhookDeliveryAttempt.id)
        ).all()
        return DeliveryDetailResponse(
            **_delivery_body(row).model_dump(),
            attempts=[
                AttemptResponse(
                    attempt=a.attempt,
                    status_code=a.status_code,
                    error=a.error,
                    duration_ms=a.duration_ms,
                    attempted_at=iso_utc(a.attempted_at),
                )
                for a in attempts
            ],
        )
