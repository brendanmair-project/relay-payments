"""Write the committed API reference from the live OpenAPI document (REL-40): `docs/guides/openapi.json` and
`docs/guides/api-reference.md`. Standard library only; it builds the document in-process, so it needs no running
server and no API key.

    cd api && python -m app.docs_export                  # writes ../docs/guides
    python -m app.docs_export --out <directory>          # elsewhere (the output directory must exist)

`tests/test_docs_export.py` fails when the committed files differ from what `generate` returns.
"""

import argparse
import json
from pathlib import Path
from typing import Any

OPENAPI_FILE = "openapi.json"
REFERENCE_FILE = "api-reference.md"
DEFAULT_OUT = (
    Path(__file__).resolve().parents[2] / "docs" / "guides"
)  # <repo>/docs/guides, or /docs/guides in the image
METHODS = ("get", "post", "put", "patch", "delete")


def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def type_text(schema: dict[str, Any]) -> str:
    """A short description of a schema: its type, with enum values and constraints."""
    if "$ref" in schema:
        return f"`{_ref_name(schema['$ref'])}`"
    if "anyOf" in schema:
        return " or ".join(type_text(member) for member in schema["anyOf"])
    if "enum" in schema:
        return "one of " + ", ".join(f"`{v}`" for v in schema["enum"])
    kind = schema.get("type", "any")
    if kind == "array":
        return "array of " + type_text(schema.get("items", {}))
    notes = [
        f"{label} {schema[key]}"
        for key, label in (
            ("minimum", "min"),
            ("maximum", "max"),
            ("minLength", "min length"),
            ("maxLength", "max length"),
        )
        if key in schema
    ]
    if "pattern" in schema:
        notes.append(f"pattern `{schema['pattern']}`")
    return f"`{kind}`" + (f" ({', '.join(notes)})" if notes else "")


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _fields(schema: dict[str, Any], schemas: dict[str, Any]) -> list[str]:
    if "$ref" in schema:
        schema = schemas[_ref_name(schema["$ref"])]
    required = set(schema.get("required", []))
    rows = ["| Field | Type | Required |", "|---|---|---|"]
    for name, prop in schema.get("properties", {}).items():
        rows.append(f"| `{name}` | {_cell(type_text(prop))} | {'yes' if name in required else 'no'} |")
    return rows


def _operation(method: str, path: str, op: dict[str, Any], schemas: dict[str, Any]) -> list[str]:
    lines = [f"## `{method.upper()} {path}`", "", op["summary"], ""]
    if op.get("description"):
        lines += [op["description"], ""]
    params = op.get("parameters", [])
    if params:
        lines += ["Parameters:", "", "| Name | In | Required | Type | Notes |", "|---|---|---|---|---|"]
        for p in params:
            note = p.get("description", "")
            lines.append(
                f"| `{p['name']}` | {p['in']} | {'yes' if p.get('required') else 'no'} | "
                f"{_cell(type_text(p['schema']))} | {_cell(note)} |"
            )
        lines.append("")
    body = op.get("requestBody")
    if body:
        schema = body["content"]["application/json"]["schema"]
        lines += ["Request body (JSON):", "", *_fields(schema, schemas), ""]
    lines += ["Responses:", "", "| Status | Meaning | Body |", "|---|---|---|"]
    for status, response in op["responses"].items():
        content = response.get("content", {}).get("application/json", {}).get("schema")
        lines.append(f"| {status} | {_cell(response['description'])} | {type_text(content) if content else '-'} |")
    lines.append("")
    return lines


def render_reference(spec: dict[str, Any]) -> str:
    schemas = spec["components"]["schemas"]
    info = spec["info"]
    lines = [
        f"# {info['title']} API reference (version {info['version']})",
        "",
        "<!-- GENERATED by `python -m app.docs_export` from the live OpenAPI document. Do not edit by hand: "
        "change the code and regenerate; a test fails when this file is out of date. -->",
        "",
        "Every endpoint requires the header `X-API-Key`; a missing or wrong key is 401 `unauthorized`. "
        'Errors share one body, `{"error": {"code", "message", "details", "correlation_id"}}`; '
        "the codes are in [authentication-and-idempotency.md](authentication-and-idempotency.md). "
        "The machine-readable document is [openapi.json](openapi.json).",
        "",
    ]
    for path, item in spec["paths"].items():
        for method in METHODS:
            if method in item:
                lines += _operation(method, path, item[method], schemas)
    lines += ["## Schemas", ""]
    for name, schema in sorted(schemas.items()):
        lines += [f"### `{name}`", "", *_fields(schema, schemas), ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_openapi(spec: dict[str, Any]) -> str:
    return json.dumps(spec, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def generate(spec: dict[str, Any]) -> dict[str, str]:
    """File name -> exact text, for both generated files."""
    return {OPENAPI_FILE: render_openapi(spec), REFERENCE_FILE: render_reference(spec)}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write docs/guides/openapi.json and api-reference.md")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output directory (default: <repo>/docs/guides)")
    args = parser.parse_args(argv)
    from app.main import app  # imported here so `generate` stays importable without building the app

    for name, text in generate(app.openapi()).items():
        with (args.out / name).open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        print(f"wrote {args.out / name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
